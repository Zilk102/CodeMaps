#!/usr/bin/env node
// Regenerates the copies of the agent files that ship inside CodeMaps from their single sources:
//   .claude/skills/codemaps-agent-autopilot/SKILL.md  -> electron/setup/templates/skillTemplate.ts
//                                                     -> the template in McpSettingsAgentSkill.tsx
//   scripts/codemaps-validate-hook.mjs                -> electron/setup/templates/hookTemplate.ts
// `setup_project` writes these copies into other projects; a test fails when they drift from the
// sources, and this script (npm run sync:templates, then npm run format) brings them back in sync.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const read = (relative) =>
  fs.readFileSync(path.join(root, relative), 'utf8').replace(/\r\n/g, '\n');
const write = (relative, text) => fs.writeFileSync(path.join(root, relative), text);

const MARKER_TOKEN = '{{CODEMAPS_FILE_MARKER}}';
const ENDPOINT = 'http://127.0.0.1:3005/mcp';

/** Escapes text for use inside a TypeScript template literal. */
const toTemplateLiteral = (text) =>
  text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const skill = read('.claude/skills/codemaps-agent-autopilot/SKILL.md').replace(
  ENDPOINT,
  '__ENDPOINT__'
);
const frontmatterEnd = skill.indexOf('\n---\n', 4) + '\n---\n'.length;
const skillWithMarker = `${skill.slice(0, frontmatterEnd)}\n${MARKER_TOKEN}\n${skill.slice(frontmatterEnd)}`;

write(
  'electron/setup/templates/skillTemplate.ts',
  `/**
 * GENERATED by scripts/sync-agent-templates.mjs from .claude/skills/codemaps-agent-autopilot/SKILL.md.
 * Do not edit by hand: change the source and run \`npm run sync:templates\`.
 */

/** The agent skill \`setup_project\` writes; \`__ENDPOINT__\` is the MCP endpoint and the marker token receives the version marker. */
export const SKILL_TEMPLATE = \`${toTemplateLiteral(skillWithMarker)}\`;
`
);

const hook = read('scripts/codemaps-validate-hook.mjs');
const shebangEnd = hook.startsWith('#!') ? hook.indexOf('\n') + 1 : 0;
const hookWithMarker = `${hook.slice(0, shebangEnd)}${MARKER_TOKEN}\n${hook.slice(shebangEnd)}`;

write(
  'electron/setup/templates/hookTemplate.ts',
  `/**
 * GENERATED by scripts/sync-agent-templates.mjs from scripts/codemaps-validate-hook.mjs.
 * Do not edit by hand: change the source and run \`npm run sync:templates\`.
 */

/** The dependency-free edit hook \`setup_project\` copies to \`.codemaps/hooks/validate.mjs\`; the marker token receives the version marker. */
export const HOOK_TEMPLATE = \`${toTemplateLiteral(hookWithMarker)}\`;
`
);

const componentFile = 'src/components/mcp-settings/McpSettingsAgentSkill.tsx';
const component = read(componentFile);
const start = component.indexOf('const SKILL_TEMPLATE = `') + 'const SKILL_TEMPLATE = `'.length;
const end = component.indexOf('\n`;\n', start) + 1;
write(
  componentFile,
  `${component.slice(0, start)}${toTemplateLiteral(skill)}${component.slice(end)}`
);
console.log('Synced skill and hook templates.');
