import type { McpStatusResourceDescriptor, McpStatusToolDescriptor } from './descriptors';

/** Reader-facing grouping of the tools; a test makes sure every tool belongs to one. */
export const TOOL_CATEGORIES: Array<{ title: string; intro: string; tools: string[] }> = [
  {
    title: 'Start here: agent-ready context',
    intro:
      'Composite tools that prepare everything an agent needs in one bounded response. Prefer these over the low-level tools.',
    tools: [
      'prepare_task_context',
      'prepare_project_context',
      'prepare_change_context',
      'prepare_change_campaign',
      'prepare_review_context',
    ],
  },
  {
    title: 'Project graph',
    intro: 'Open a project and navigate its dependency graph.',
    tools: ['analyze_project', 'get_graph_context', 'get_node_dependencies', 'search_graph'],
  },
  {
    title: 'Reading code cheaply',
    intro: 'Understand a file or find a declaration without reading whole files.',
    tools: ['get_semantic_skeleton', 'search_signatures'],
  },
  {
    title: 'Impact of a change',
    intro: 'What a change touches before you make it.',
    tools: ['get_blast_radius', 'calculate_blast_radius_v2', 'analyze_pr_impact'],
  },
  {
    title: 'Quality and architecture',
    intro: 'Find problems, validate your edits and plan refactoring.',
    tools: [
      'validate_architecture_changes',
      'get_health_score',
      'get_architecture_overview',
      'detect_patterns',
      'analyze_decomposition',
      'find_duplicates',
      'run_security_scan',
      'analyze_activity_heatmap',
    ],
  },
];

const ENDPOINT = 'http://127.0.0.1:3005/mcp';

/** Renders the Markdown tools reference: tools grouped by `TOOL_CATEGORIES` (names missing from `tools` are skipped), then all resources. Output is deterministic and ends with a newline. */
export const renderToolsReference = (
  tools: McpStatusToolDescriptor[],
  resources: McpStatusResourceDescriptor[]
): string => {
  const byName = new Map(tools.map((tool) => [tool.name, tool]));
  const lines: string[] = [
    '# MCP tools and resources',
    '',
    '<!-- Generated by `npm run docs:mcp` from electron/mcp/descriptors.ts. Do not edit by hand. -->',
    '',
    `CodeMaps serves MCP over Streamable HTTP at \`${ENDPOINT}\` while the app is running. It exposes ${tools.length} tools and ${resources.length} resources. See [Using CodeMaps with Claude](CLAUDE_INTEGRATION.md) for connecting a client.`,
    '',
    'Every tool response is bounded to a fixed size; when something was cut it says so under `_compaction`, and most list-returning tools accept a `limit`.',
    '',
  ];

  for (const category of TOOL_CATEGORIES) {
    lines.push(`## ${category.title}`, '', category.intro, '');
    for (const name of category.tools) {
      const tool = byName.get(name);
      if (!tool) continue;
      lines.push(`### \`${tool.name}\``, '', tool.description, '');
      if (tool.recommendedWhen) lines.push(`**Use when:** ${tool.recommendedWhen}`, '');
    }
  }

  lines.push('## Resources', '');
  for (const resource of resources) {
    lines.push(`### \`${resource.uri}\``, '', resource.description, '');
  }

  return `${lines.join('\n').trimEnd()}\n`;
};
