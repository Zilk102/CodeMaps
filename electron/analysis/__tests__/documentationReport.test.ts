import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { afterAll, describe, expect, it } from 'vitest';
import {
  analyzeDocumentation,
  analyzeDocumentationSource,
  buildDocumentationReport,
  DocumentationIndex,
  documentationPolicy,
} from '../documentation';
import { analyze, source } from './documentationTestKit';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'codemaps-docs-'));
afterAll(() => fs.rmSync(dir, { recursive: true, force: true }));

const write = (name: string, text: string): string => {
  const file = path.join(dir, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return file;
};

describe('exempt and unsupported files', () => {
  it.each([
    ['/p/service.test.ts', 'test'],
    ['/p/__tests__/helper.ts', 'test'],
    ['/p/pkg/server_test.go', 'test'],
    ['/p/pkg/test_server.py', 'test'],
    ['/p/src/gen/client.ts', 'generated'],
    ['/p/api/api.pb.go', 'generated'],
    ['/p/types/index.d.ts', 'generated'],
    ['/p/dist/app.min.js', 'generated'],
  ])('%s is exempt (%s)', async (file, reason) => {
    const result = await analyze(file, 'export function undocumented() {}\n');
    expect(result).toMatchObject({
      exempt: true,
      exemptReason: reason,
      header: 'n/a',
      symbols: [],
    });
  });

  it('exempts a file that says it was generated', async () => {
    const result = await analyze(
      '/p/schema.ts',
      source('// Code generated by protoc. DO NOT EDIT.', 'export function f() {}')
    );
    expect(result.exempt).toBe(true);
    const marked = await analyze('/p/other.ts', source('/** @generated */', 'export const a = 1;'));
    expect(marked.exempt).toBe(true);
  });

  it.each([
    '/p/README.md',
    '/p/a.json',
    '/p/a.css',
    '/p/a.html',
    '/p/a.yaml',
    '/p/a.txt',
    '/p/Makefile',
  ])('does not measure %s', async (file) => {
    expect(await analyzeDocumentationSource(file, 'text')).toBeNull();
  });
});

describe('documentation report', () => {
  const good = source(
    '/** Helpers that format money amounts for display. */',
    '/** Formats an amount of cents as a currency string. */',
    'export function format(cents: number) { return String(cents); }'
  );
  const poor = source(
    'export function a() {}',
    'export function b() {}',
    'export class C {}',
    '/** Gets the user. */',
    'export function getUser() {}'
  );

  it('computes coverage, offenders, the undocumented list and language stats', async () => {
    const results = [
      await analyze('/p/good.ts', good),
      await analyze('/p/poor.ts', poor),
      await analyze(
        '/p/clean.py',
        'def ok():\n    """Does one useful thing for callers."""\n    pass\n'
      ),
      await analyze('/p/skip.test.ts', 'export function t() {}'),
    ];
    const report = buildDocumentationReport(results);
    expect(report).toMatchObject({
      analyzedFiles: 3,
      exemptFiles: 1,
      requiredSymbols: 6,
      documentedSymbols: 3,
      coveragePercent: 50,
    });
    expect(report.undocumented).toEqual([
      { file: '/p/poor.ts', line: 1, name: 'a', kind: 'function' },
      { file: '/p/poor.ts', line: 2, name: 'b', kind: 'function' },
      { file: '/p/poor.ts', line: 3, name: 'C', kind: 'class' },
    ]);
    expect(report.topOffenders).toEqual([
      { file: '/p/poor.ts', missing: 3, required: 4, coverage: 25 },
    ]);
    expect(report.lowQuality).toEqual([
      { file: '/p/poor.ts', line: 5, name: 'getUser', kind: 'function', quality: 'echo' },
    ]);
    expect(report.byLanguage).toEqual([
      {
        language: 'python',
        files: 1,
        requiredSymbols: 1,
        documentedSymbols: 1,
        coverage: 100,
        filesWithoutHeader: 0,
      },
      {
        language: 'typescript',
        files: 2,
        requiredSymbols: 5,
        documentedSymbols: 2,
        coverage: 40,
        filesWithoutHeader: 0,
      },
    ]);
  });

  it('lists files without a header and counts commented-out code', async () => {
    const longFile = source(
      ...Array.from(
        { length: documentationPolicy.MIN_HEADER_FILE_LINES },
        (_, i) => `export const v${i} = ${i};`
      )
    );
    const code = source(
      'export const a = 1;',
      '// const x = compute(1);',
      '// run(x);',
      '// stop(x);'
    );
    const report = buildDocumentationReport([
      await analyze('/p/long.ts', longFile),
      await analyze('/p/old.ts', code),
    ]);
    expect(report.filesWithoutHeader).toEqual(['/p/long.ts']);
    expect(report.commentedOutCodeBlocks).toBe(1);
    expect(report.byLanguage[0].filesWithoutHeader).toBe(1);
  });

  it('reports 100 percent for a project that requires nothing', () => {
    expect(buildDocumentationReport([]).coveragePercent).toBe(100);
  });

  it('is deterministic whatever the order of the input', async () => {
    const results = [
      await analyze('/p/b.ts', poor),
      await analyze('/p/a.ts', poor),
      await analyze('/p/c.go', 'package c\n\nfunc Exported() {}\n'),
    ];
    const forward = buildDocumentationReport(results);
    const backward = buildDocumentationReport([...results].reverse());
    expect(JSON.stringify(backward)).toBe(JSON.stringify(forward));
    expect(forward.topOffenders.map((entry) => entry.file)).toEqual([
      '/p/a.ts',
      '/p/b.ts',
      '/p/c.go',
    ]);
  });

  it('keeps at most the policy limit of top offenders', async () => {
    const results = await Promise.all(
      Array.from({ length: documentationPolicy.MAX_TOP_OFFENDERS + 5 }, (_, i) =>
        analyze(`/p/f${String(i).padStart(2, '0')}.ts`, 'export function f() {}')
      )
    );
    expect(buildDocumentationReport(results).topOffenders).toHaveLength(
      documentationPolicy.MAX_TOP_OFFENDERS
    );
  });
});

describe('DocumentationIndex', () => {
  it('reads files from disk, skips unsupported and oversized ones, and caches by mtime', async () => {
    const root = path.join(dir, 'project');
    const a = write('project/src/a.ts', 'export function a() {}\n');
    const b = write('project/src/b.py', 'def b():\n    """Does something for the caller."""\n');
    const notes = write('project/notes.md', '# notes');
    const huge = write(
      'project/huge.ts',
      `export const x = "${'a'.repeat(documentationPolicy.MAX_FILE_BYTES)}";`
    );
    const missing = path.join(root, 'src', 'missing.ts');
    const index = new DocumentationIndex();

    const first = await index.refresh(root, [a, b, notes, huge, missing, a]);
    expect(first.files.map((f) => path.basename(f.file))).toEqual(['a.ts', 'b.py']);
    expect(first.undocumented.map((s) => s.name)).toEqual(['a']);

    const second = await index.refresh(root, [a, b]);
    expect(second.files[0]).toBe(first.files[0]);
    expect(index.peek(root)).toBe(second);

    fs.writeFileSync(a, '/** Adds the numbers together. */\nexport function a() {}\n');
    fs.utimesSync(a, new Date(), new Date(Date.now() + 5000));
    const third = await index.refresh(root, [a, b]);
    expect(third.files[0]).not.toBe(first.files[0]);
    expect(third.undocumented).toEqual([]);
    expect(third.coveragePercent).toBe(100);

    index.clear();
    expect(index.peek(root)).toBeNull();
  });

  it('analyzes many files with bounded concurrency through analyzeDocumentation', async () => {
    const files = Array.from({ length: 80 }, (_, i) =>
      write(
        `many/f${i}.ts`,
        `/** Number ${i} of the generated fixtures. */\nexport function f${i}() {}\n`
      )
    );
    const report = await analyzeDocumentation(files, path.join(dir, 'many'));
    expect(report.analyzedFiles).toBe(80);
    expect(report.coveragePercent).toBe(100);
  });
});
